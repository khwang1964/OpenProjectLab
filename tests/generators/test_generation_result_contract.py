"""Verify the shared result contract across built-in generators."""

from __future__ import annotations

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol, cast

import pytest

from generator.core.models import (
    GenerateRequest,
    GenerationResult,
    RuntimeOptions,
    WriteResult,
)
from generator.generators.bootstrap_generator import BootstrapGenerator
from generator.generators.course_generator import CourseGenerator
from generator.generators.week_generator import WeekGenerator


class Generator(Protocol):
    """Describe the generator interface exercised by contract tests."""

    name: str

    def generate(self, request: GenerateRequest) -> GenerationResult:
        """Generate content and return the shared result contract."""
        ...

    def run(self, request: GenerateRequest) -> GenerationResult:
        """Run the generator through its registry-compatible alias."""
        ...


@dataclass(frozen=True, slots=True)
class GeneratorCase:
    """Define one built-in generator contract scenario."""

    name: str
    factory: Callable[[Path, Path], Generator]
    context: Mapping[str, object]
    templates: tuple[str, ...]
    expected_paths: Callable[[Path], tuple[Path, ...]]


CASES = (
    GeneratorCase(
        name="bootstrap",
        factory=lambda templates, output: BootstrapGenerator(templates, output),
        context={"project_slug": "contract-course"},
        templates=tuple(BootstrapGenerator.TEMPLATE_MANIFEST.values()),
        expected_paths=lambda output: tuple(
            output / "contract-course" / name for name in BootstrapGenerator.TEMPLATE_MANIFEST
        ),
    ),
    GeneratorCase(
        name="course",
        factory=lambda templates, output: CourseGenerator(templates, output),
        context={"course_name": "Contract Course"},
        templates=("course/README.md.j2",),
        expected_paths=lambda output: (output / "README.md",),
    ),
    GeneratorCase(
        name="week",
        factory=lambda templates, output: WeekGenerator(templates, output),
        context={"week": 1},
        templates=("week/README.md.j2",),
        expected_paths=lambda output: (output / "week-01" / "README.md",),
    ),
)


@pytest.fixture(params=CASES, ids=lambda case: case.name)
def generator_case(request: pytest.FixtureRequest) -> GeneratorCase:
    """Return each built-in generator contract scenario."""
    return cast(GeneratorCase, request.param)


def _prepare_generator(
    tmp_path: Path,
    case: GeneratorCase,
    *,
    output_name: str = "output",
) -> tuple[Generator, Path]:
    """Create minimal templates and return a configured generator."""
    template_root = tmp_path / "templates"
    output_root = tmp_path / output_name

    for template_name in case.templates:
        template_path = template_root / template_name
        template_path.parent.mkdir(parents=True, exist_ok=True)
        template_path.write_text("generated by contract test\n", encoding="utf-8")

    return case.factory(template_root, output_root), output_root


def _make_request(
    case: GeneratorCase,
    target: Path,
    *,
    dry_run: bool = False,
    record_manifest: bool = True,
) -> GenerateRequest:
    """Build a canonical request without mutating the case context."""
    values = dict(case.context)
    values["record_manifest"] = record_manifest
    return GenerateRequest(
        generator_name=case.name,
        target=target,
        values=values,
        options=RuntimeOptions(dry_run=dry_run),
    )


def test_generate_returns_shared_result_contract(
    tmp_path: Path,
    generator_case: GeneratorCase,
) -> None:
    """Require every generator to expose ordered immutable write results."""
    generator, output_root = _prepare_generator(tmp_path, generator_case)
    request = _make_request(generator_case, output_root)

    result = generator.generate(request)

    assert type(result) is GenerationResult
    assert result.generator_name == generator.name == generator_case.name
    assert isinstance(result.writes, tuple)
    assert all(isinstance(write, WriteResult) for write in result.writes)
    assert result.affected_paths == tuple(write.path for write in result.writes)
    assert result.affected_paths == generator_case.expected_paths(output_root)
    assert result.dry_run is False
    assert result.manifest_updated is True


def test_dry_run_preserves_contract_without_writing(
    tmp_path: Path,
    generator_case: GeneratorCase,
) -> None:
    """Require dry-run results to retain metadata without filesystem writes."""
    generator, output_root = _prepare_generator(tmp_path, generator_case)
    request = _make_request(generator_case, output_root, dry_run=True)

    result = generator.generate(request)

    assert type(result) is GenerationResult
    assert result.generator_name == generator_case.name
    assert result.affected_paths == generator_case.expected_paths(output_root)
    assert result.dry_run is True
    assert result.manifest_updated is False
    assert not output_root.exists()


def test_run_returns_shared_result_contract(
    tmp_path: Path,
    generator_case: GeneratorCase,
) -> None:
    """Require the registry-compatible run alias to use the same contract."""
    generator, output_root = _prepare_generator(tmp_path, generator_case)
    request = _make_request(generator_case, output_root, dry_run=True)

    result = generator.run(request)

    assert type(result) is GenerationResult
    assert result.generator_name == generator_case.name
    assert isinstance(result.writes, tuple)
    assert all(isinstance(write, WriteResult) for write in result.writes)


def test_manifest_recording_flag_is_reported_consistently(
    tmp_path: Path,
    generator_case: GeneratorCase,
) -> None:
    """Require all generators to report whether they updated a manifest."""
    enabled_generator, enabled_output = _prepare_generator(
        tmp_path,
        generator_case,
        output_name="manifest-enabled",
    )
    disabled_generator, disabled_output = _prepare_generator(
        tmp_path,
        generator_case,
        output_name="manifest-disabled",
    )

    enabled_request = _make_request(generator_case, enabled_output)
    disabled_request = _make_request(
        generator_case,
        disabled_output,
        record_manifest=False,
    )
    enabled = enabled_generator.generate(enabled_request)
    disabled = disabled_generator.generate(disabled_request)

    assert enabled.manifest_updated is True
    assert disabled.manifest_updated is False
